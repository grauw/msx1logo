FORCLR: equ 0F3E9H
BAKCLR: equ 0F3EAH
BDRCLR: equ 0F3EBH

	org 4000H

	db "AB"
	dw MSX1Logo_Main
	dw 0, 0, 0, 0, 0, 0

MSX1Logo_Main:
	call MSX1Logo_InitScreen
	call MSX1Logo_DrawPatternNames
	call MSX1Logo_DrawPatterns
	call MSX1Logo_DrawColors
	jr $

MSX1Logo_InitScreen:
	ld a,15
	ld (FORCLR),a
	ld a,4
	ld (BAKCLR),a
	ld a,4
	ld (BDRCLR),a
	ld a,2
	call CHGMOD
	ret

MSX1Logo_DrawPatternNames: PROC
	ld hl,(GRPNAM)
	ld de,100H
	add hl,de
	ex de,hl
	ld hl,MSX1Logo_names
	ld bc,MSX1Logo_namesCount
	call LDIRVM
	ret
	ENDP

MSX1Logo_DrawPatterns: PROC
	ld hl,(GRPCGP)
	ld de,180H * 8
	add hl,de
	ex de,hl
	ld hl,MSX1Logo_patterns
	ld bc,MSX1Logo_patternsCount
	call LDIRVM
	ret
	ENDP

MSX1Logo_DrawColors: PROC
	ld hl,(GRPCOL)
	ld de,0E3H * 8
	add hl,de
	ld bc,26 * 8
	ld a,0F1H
	call FILVRM
	ld hl,(GRPCOL)
	ld de,181H * 8
	add hl,de
	ld bc,MSX1Logo_patternsCount - 8
	ld a,0F1H
	call FILVRM
	ld hl,(GRPCOL)
	ld de,203H * 8
	add hl,de
	ld bc,26 * 8
	ld a,0F1H
	call FILVRM
	ret
	ENDP

